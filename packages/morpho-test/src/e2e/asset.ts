/**
 * Returns a chain's registered wNative or the fallback token and whether callers must install code.
 *
 * @param chainId - Chain to select the asset for.
 * @returns The token address and whether the caller must install its code, as `requiresInstall`.
 * @throws {UnsupportedChainIdError} When `chainId` has no address registry in
 *   `@morpho-org/morpho-ts`.
 * @example
 * ```ts
 * import { ChainId } from "@morpho-org/morpho-ts";
 * import { E2E_ASSET, getE2eAsset } from "@morpho-org/morpho-test";
 *
 * getE2eAsset(ChainId.ArcMainnet); // { address: E2E_ASSET, requiresInstall: true }
 * ```
 */
export const getE2eAsset = (
  chainId: number,
): { readonly address: Address; readonly requiresInstall: boolean } => {
  const { wNative } = getChainAddresses(chainId);
  return wNative == null
    ? { address: E2E_ASSET, requiresInstall: true }
    : { address: wNative, requiresInstall: false };
};
