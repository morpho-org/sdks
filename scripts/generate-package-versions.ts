#!/usr/bin/env node

import {
  existsSync,
  lstatSync,
  readdirSync,
  readFileSync,
  realpathSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { isPathInside } from "./paths.ts";

const DEFAULT_REPOSITORY_ROOT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "..",
);

/**
 * Renders a browser-safe module containing the installed package version.
 *
 * @param version Package version to embed.
 * @param packageName Installed package name.
 * @returns Generated TypeScript source.
 */
export function renderPackageVersionSource(
  version: string,
  packageName: string,
): string {
  if (typeof version !== "string" || version.length === 0) {
    throw new Error("Package version must be a non-empty string.");
  }

  if (
    typeof packageName !== "string" ||
    !/^@[a-z0-9-]+\/[a-z0-9-]+$/.test(packageName)
  ) {
    throw new Error("Package name must be a scoped npm package name.");
  }
  return `// Generated by scripts/generate-package-versions.ts. Do not edit.\n\n/** Installed ${packageName} package version. */\nexport const version = ${JSON.stringify(version)};\n`;
}

/**
 * Reads a package manifest and returns its generated version source.
 *
 * @param options Generation options.
 * @returns Generated TypeScript source.
 */
export function getPackageVersionSource(options: {
  cwd?: string;
  manifestPath: string;
}): string {
  const basePath = realpathSync(options.cwd ?? DEFAULT_REPOSITORY_ROOT);
  const manifestPath = resolve(basePath, options.manifestPath);
  if (!isPathInside(basePath, manifestPath)) {
    throw new Error(`Invalid package manifest path "${options.manifestPath}".`);
  }

  const stats = lstatSync(manifestPath);
  if (!stats.isFile() || !isPathInside(basePath, realpathSync(manifestPath))) {
    throw new Error(`Invalid package manifest path "${options.manifestPath}".`);
  }

  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as {
    version: string;
    name: string;
  };

  return renderPackageVersionSource(manifest.version, manifest.name);
}

/**
 * Writes version sources for every workspace package, including private ones.
 *
 * @param options Generation options.
 * @returns Repository-relative generated source paths.
 */
export function generatePackageVersions(
  options: { cwd?: string } = {},
): string[] {
  const basePath = realpathSync(options.cwd ?? DEFAULT_REPOSITORY_ROOT);
  const paths: string[] = [];
  for (const entry of readdirSync(resolve(basePath, "packages"), {
    withFileTypes: true,
  }).sort((a, b) => a.name.localeCompare(b.name))) {
    const manifestPath = `packages/${entry.name}/package.json`;
    if (!entry.isDirectory() || !existsSync(resolve(basePath, manifestPath)))
      continue;
    const source = getPackageVersionSource({ cwd: basePath, manifestPath });
    const sourceRelativePath = `packages/${entry.name}/src/version.ts`;
    const sourcePath = resolve(basePath, sourceRelativePath);
    const sourceParentPath = realpathSync(dirname(sourcePath));
    if (
      !isPathInside(basePath, sourcePath) ||
      !isPathInside(basePath, sourceParentPath) ||
      (existsSync(sourcePath) &&
        (!lstatSync(sourcePath).isFile() ||
          !isPathInside(basePath, realpathSync(sourcePath))))
    ) {
      throw new Error(
        `Invalid package version source path "${sourceRelativePath}".`,
      );
    }

    writeFileSync(sourcePath, source);
    paths.push(sourceRelativePath);
  }
  return paths;
}

if (
  process.argv[1] != null &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  generatePackageVersions();
}
