#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** Repository-relative Midnight SDK manifest path. */
export const MIDNIGHT_PACKAGE_MANIFEST_PATH =
  "packages/midnight-sdk/package.json";
/** Repository-relative generated Midnight SDK version source path. */
export const MIDNIGHT_VERSION_SOURCE_PATH =
  "packages/midnight-sdk/src/api/version.generated.ts";

const DEFAULT_REPOSITORY_ROOT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../..",
);

/**
 * Renders the browser-safe source module containing the Midnight SDK version.
 *
 * @param {string} version Package version to embed.
 * @returns {string} Generated TypeScript source.
 */
export function renderMidnightPackageVersionSource(version) {
  if (typeof version !== "string" || version.length === 0) {
    throw new Error("Midnight SDK package version must be a non-empty string.");
  }

  return `// Generated by scripts/release/generate-midnight-package-version.mjs. Do not edit.\n\n/** @internal Installed Midnight SDK package version. */\nexport const MIDNIGHT_SDK_VERSION = ${JSON.stringify(version)};\n`;
}

/**
 * Reads the Midnight SDK manifest and returns its generated version source.
 *
 * @param {{ cwd?: string }} options Generation options.
 * @returns {string} Generated TypeScript source.
 */
export function getMidnightPackageVersionSource(options = {}) {
  const cwd = options.cwd ?? DEFAULT_REPOSITORY_ROOT;
  const manifestPath = resolve(cwd, MIDNIGHT_PACKAGE_MANIFEST_PATH);
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));

  return renderMidnightPackageVersionSource(manifest.version);
}

/**
 * Writes the Midnight SDK version source from the current package manifest.
 *
 * @param {{ cwd?: string }} options Generation options.
 * @returns {string} Generated TypeScript source.
 */
export function generateMidnightPackageVersion(options = {}) {
  const cwd = options.cwd ?? DEFAULT_REPOSITORY_ROOT;
  const source = getMidnightPackageVersionSource({ cwd });
  writeFileSync(resolve(cwd, MIDNIGHT_VERSION_SOURCE_PATH), source);

  return source;
}

if (
  process.argv[1] != null &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  generateMidnightPackageVersion();
}
